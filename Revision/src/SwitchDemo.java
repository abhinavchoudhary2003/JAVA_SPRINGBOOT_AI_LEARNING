public class SwitchDemo {
    public static void main(String[] args) {
        int id = 4;
        switch (id){
            case 1:
                System.out.println(id);
                break;
            case 2:
                System.out.println(id);
                break;
            case 3:
                System.out.println(id);
                break;
            case 4:
                System.out.println(id);
                break;
            case 5:
                System.out.println(id);
                break;
            default:
                System.out.println("id doesn't exist"); break;
    }
}
}